//! 配置中的 Windows VK 逻辑键码 → macOS Carbon kVK 虚拟键码（美式布局）。
//! 媒体键由 macOS 系统定义事件处理，不走普通键盘事件映射。

/// 返回普通键盘事件使用的 kVK；不支持的键与媒体键返回 None。
/// 通用修饰键取左侧，Win 对应 Command；VK_RETURN 无法区分主键盘与小键盘 Enter。
pub fn vk_to_kvk(vk: u16) -> Option<u16> {
    const LETTERS: [u16; 26] = [
        0x00, 0x0B, 0x08, 0x02, 0x0E, 0x03, 0x05, 0x04, 0x22, 0x26, 0x28, 0x25, 0x2E,
        0x2D, 0x1F, 0x23, 0x0C, 0x0F, 0x01, 0x11, 0x20, 0x09, 0x0D, 0x07, 0x10, 0x06,
    ];
    const DIGITS: [u16; 10] = [0x1D, 0x12, 0x13, 0x14, 0x15, 0x17, 0x16, 0x1A, 0x1C, 0x19];
    const FUNCTION: [u16; 20] = [
        0x7A, 0x78, 0x63, 0x76, 0x60, 0x61, 0x62, 0x64, 0x65, 0x6D,
        0x67, 0x6F, 0x69, 0x6B, 0x71, 0x6A, 0x40, 0x4F, 0x50, 0x5A,
    ];
    const KEYPAD: [u16; 10] = [0x52, 0x53, 0x54, 0x55, 0x56, 0x57, 0x58, 0x59, 0x5B, 0x5C];
    Some(match vk {
        0x41..=0x5A => LETTERS[(vk - 0x41) as usize],
        0x30..=0x39 => DIGITS[(vk - 0x30) as usize],
        0x70..=0x83 => FUNCTION[(vk - 0x70) as usize],
        0x60..=0x69 => KEYPAD[(vk - 0x60) as usize],
        0x08 => 0x33, // 退格键 → Delete
        0x09 => 0x30, // 制表键
        0x0C | 0x90 => 0x47, // Clear / 小键盘 NumLock 位置 → KeypadClear
        0x0D => 0x24, // 回车键
        0x10 | 0xA0 => 0x38, // 通用/左侧 Shift
        0x11 | 0xA2 => 0x3B, // 通用/左侧 Control
        0x12 | 0xA4 => 0x3A, // 通用/左侧 Alt → Option
        0x14 => 0x39, // 大写锁定键
        0x1B => 0x35, // 退出键
        0x20 => 0x31, // 空格键
        0x21 => 0x74, // 向上翻页
        0x22 => 0x79, // 向下翻页
        0x23 => 0x77, // 文档末尾
        0x24 => 0x73, // 文档开头
        0x25 => 0x7B, // 向左箭头
        0x26 => 0x7E, // 向上箭头
        0x27 => 0x7C, // 向右箭头
        0x28 => 0x7D, // 向下箭头
        0x2E => 0x75, // 向前删除键 → ForwardDelete
        0x2F => 0x72, // 帮助键
        0x5B => 0x37, // 左侧 Win → Command
        0x5C => 0x36, // 右侧 Win → RightCommand
        0x6A => 0x43, // 小键盘乘号
        0x6B => 0x45, // 小键盘加号
        0x6D => 0x4E, // 小键盘减号
        0x6E => 0x41, // 小键盘小数点
        0x6F => 0x4B, // 小键盘除号
        0x92 => 0x51, // 小键盘等号（VK_OEM_NEC_EQUAL）
        0xA1 => 0x3C, // 右侧 Shift
        0xA3 => 0x3E, // 右侧 Control
        0xA5 => 0x3D, // 右侧 Alt → RightOption
        0xBA => 0x29, // 美式分号
        0xBB => 0x18, // 美式等号
        0xBC => 0x2B, // 美式逗号
        0xBD => 0x1B, // 美式减号
        0xBE => 0x2F, // 美式句点
        0xBF => 0x2C, // 美式斜线
        0xC0 => 0x32, // 美式反引号
        0xDB => 0x21, // 美式左方括号
        0xDC => 0x2A, // 美式反斜线
        0xDD => 0x1E, // 美式右方括号
        0xDE => 0x27, // 美式单引号
        _ => return None,
    })
}

/// kVK → 配置中的 VK 逻辑键码；多对一映射取通用修饰键与 Clear。
/// 小键盘 Enter 与主键盘 Enter 对应同一个 VK_RETURN；未知键不猜测映射。
pub fn kvk_to_vk(kvk: u16) -> Option<u16> {
    if kvk == 0x4C { return Some(0x0D); }
    (0..=0xFE).find(|&vk| vk_to_kvk(vk) == Some(kvk))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reverse_mapping_round_trips_all_supported_positions() {
        for kvk in 0..=0x7F {
            if let Some(vk) = kvk_to_vk(kvk) {
                assert_eq!(vk_to_kvk(vk), Some(if kvk == 0x4C { 0x24 } else { kvk }));
            }
        }
        for vk in 0..=0xFE {
            if let Some(kvk) = vk_to_kvk(vk) { assert!(kvk_to_vk(kvk).is_some()); }
        }
        assert_eq!(kvk_to_vk(0x38), Some(0x10));
        assert_eq!(kvk_to_vk(0x3B), Some(0x11));
        assert_eq!(kvk_to_vk(0x3A), Some(0x12));
        assert_eq!(kvk_to_vk(0x3C), Some(0xA1));
        assert_eq!(kvk_to_vk(0x36), Some(0x5C));
        assert_eq!(kvk_to_vk(0x47), Some(0x0C));
        assert_eq!(kvk_to_vk(0x4C), Some(0x0D));
        assert_eq!(kvk_to_vk(0xFFFF), None);
        assert_eq!(kvk_to_vk(0x7F), None);
    }

    #[test]
    fn letters_and_digits_use_ansi_positions() {
        for (vk, kvk) in [(0x41, 0x00), (0x53, 0x01), (0x5A, 0x06), (0x51, 0x0C), (0x30, 0x1D), (0x31, 0x12), (0x39, 0x19)] {
            assert_eq!(vk_to_kvk(vk), Some(kvk));
        }
    }

    #[test]
    fn editing_and_navigation_keys() {
        for (vk, kvk) in [
            (0x0D, 0x24), (0x09, 0x30), (0x20, 0x31), (0x08, 0x33), (0x1B, 0x35),
            (0x25, 0x7B), (0x27, 0x7C), (0x28, 0x7D), (0x26, 0x7E),
            (0x2E, 0x75), (0x24, 0x73), (0x23, 0x77), (0x21, 0x74), (0x22, 0x79),
        ] {
            assert_eq!(vk_to_kvk(vk), Some(kvk));
        }
    }

    #[test]
    fn modifiers_preserve_sides_and_win_means_command() {
        for (vk, kvk) in [
            (0x5B, 0x37), (0x5C, 0x36), (0x10, 0x38), (0xA0, 0x38), (0xA1, 0x3C),
            (0x12, 0x3A), (0xA4, 0x3A), (0xA5, 0x3D), (0x11, 0x3B), (0xA2, 0x3B), (0xA3, 0x3E), (0x14, 0x39),
        ] {
            assert_eq!(vk_to_kvk(vk), Some(kvk));
        }
    }

    #[test]
    fn function_keys_f1_through_f20() {
        let expected = [0x7A, 0x78, 0x63, 0x76, 0x60, 0x61, 0x62, 0x64, 0x65, 0x6D, 0x67, 0x6F, 0x69, 0x6B, 0x71, 0x6A, 0x40, 0x4F, 0x50, 0x5A];
        for (i, kvk) in expected.into_iter().enumerate() {
            assert_eq!(vk_to_kvk(0x70 + i as u16), Some(kvk), "F{}", i + 1);
        }
    }

    #[test]
    fn keypad_and_us_punctuation() {
        for (vk, kvk) in [
            (0x60, 0x52), (0x61, 0x53), (0x69, 0x5C), (0x6A, 0x43), (0x6B, 0x45), (0x6D, 0x4E),
            (0x6E, 0x41), (0x6F, 0x4B), (0x90, 0x47), (0x92, 0x51),
            (0xBA, 0x29), (0xBB, 0x18), (0xBC, 0x2B), (0xBD, 0x1B), (0xBE, 0x2F), (0xBF, 0x2C),
            (0xC0, 0x32), (0xDB, 0x21), (0xDC, 0x2A), (0xDD, 0x1E), (0xDE, 0x27),
        ] {
            assert_eq!(vk_to_kvk(vk), Some(kvk));
        }
    }

    #[test]
    fn media_and_unsupported_keys_have_no_keyboard_mapping() {
        for vk in 0xAD..=0xB3 {
            assert_eq!(vk_to_kvk(vk), None);
        }
        for vk in [0, 0x01, 0x6C, 0x84, 0x87, 0xFF, 0x100, u16::MAX] {
            assert_eq!(vk_to_kvk(vk), None);
        }
    }
}
